    private async Task RunLivePageAsync(string endpoint, Func<int, string> url)
    {
        var requests = new List<string>(); var fetch = Fetcher(url, requests);
        (await fetch(1)).Total.Should().Be(Expected, "total is the number of locally visible listings of the account");

        // Global integrity: read every announced page and compare identities (sets, never positions) with what was seeded.
        var (rows, total, announcedPages) = await LivePage01.CollectAllAsync(fetch);
        var actual = rows.Select(r => r.Id).ToList(); var unique = actual.ToHashSet(StringComparer.Ordinal); var expected = _expectedIds.ToHashSet(StringComparer.Ordinal);
        var missing = expected.Except(unique).Count(); var duplicate = actual.Count - unique.Count; var unexpected = unique.Except(expected).Count();
        total.Should().Be(Expected); announcedPages.Should().Be(2);
        rows.GroupBy(r => r.Page).ToDictionary(g => g.Key, g => g.Count()).Should().BeEquivalentTo(new Dictionary<int, int> { [1] = 100, [2] = 50 }, "page 1 holds 100 and page 2 holds 50");
        unique.Count.Should().Be(Expected, "150 positions are not enough: 150 DISTINCT identities are required"); missing.Should().Be(0); duplicate.Should().Be(0); unexpected.Should().Be(0);

        // Choose X beyond page 1 and Y on a different page, from the page membership the server itself just reported (ordering is used only to make the choice reproducible).
        var byPage = rows.GroupBy(r => r.Page).ToDictionary(g => g.Key, g => g.Select(r => r.Id).OrderBy(i => i, StringComparer.Ordinal).ToArray());
        var x = byPage[2][byPage[2].Length / 2]; var y = byPage[1][byPage[1].Length / 3];
        rows.Single(r => r.Id == x).Page.Should().BeGreaterThan(1); rows.Single(r => r.Id == y).Page.Should().NotBe(rows.Single(r => r.Id == x).Page);

        requests.Clear();
        var both = await LivePage01.RunAsync(fetch, [x, y]);
        both.FoundCount.Should().Be(2); both.MissingCount.Should().Be(0); both.DuplicateCount.Should().Be(0); both.Pages.Should().BeGreaterThanOrEqualTo(2);
        both.Pages.Should().BeLessThanOrEqualTo(both.MaxPages); requests.Count.Should().BeLessThanOrEqualTo((int)Math.Ceiling(total / 100.0), "never exceeds ceil(total/100) requests"); requests.Count.Should().Be(both.Pages);

        requests.Clear();
        var onlyY = await LivePage01.RunAsync(fetch, [y]);
        onlyY.FoundCount.Should().Be(1); onlyY.Pages.Should().Be(1, "found = T stops the traversal on the first page that holds the target"); requests.Count.Should().Be(1);
        requests.Clear();
        var onlyX = await LivePage01.RunAsync(fetch, [x]);
        onlyX.FoundCount.Should().Be(1); onlyX.Pages.Should().Be(2, "the search walks to the page that actually holds X"); requests.Count.Should().Be(2);

        requests.Clear();
        var absent = await LivePage01.RunAsync(fetch, ["MLB0000NOTSEEDED"]);
        absent.MissingCount.Should().Be(1); absent.Pages.Should().Be(2, "a target that is not there is reported missing only after the last page"); requests.Count.Should().BeLessThanOrEqualTo(2);

        output.WriteLine(Line(endpoint, Expected, announcedPages, unique.Count, missing, duplicate, unexpected, announcedPages, "PASS"));
        output.WriteLine($"LIVE-PAGE-01 [{endpoint}] X on page {rows.Single(r => r.Id == x).Page}, Y on page {rows.Single(r => r.Id == y).Page}; helper pages={both.Pages}/{both.MaxPages}, missingCount={both.MissingCount}, duplicateCount={both.DuplicateCount}");
    }


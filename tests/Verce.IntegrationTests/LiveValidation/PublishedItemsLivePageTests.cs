/// <summary>One page of the repository envelope <c>{items, page, pageSize, total}</c>, reduced to identities.</summary>
public sealed record LivePage(IReadOnlyList<string> Ids, int Page, int PageSize, int Total);

/// <summary>The safe output of LIVE-PAGE-01 (handoff "Reusable live procedures"): counts only, the missing ids are returned for the local worksheet and never printed by the test.</summary>
public sealed record LivePageResult(int TargetCount, int FoundCount, int Pages, int MaxPages, int MissingCount, int DuplicateCount, int UnexpectedCount, IReadOnlyList<string> MissingIds);

/// <summary>
/// LIVE-PAGE-01 — locate listings by identity across pages, implemented ONCE as this helper and mirrored step by step in the operator procedure (handoff, D12(a)).
/// It searches by identity, never by position, and never assumes an order: the only things it reads from a response are the ids, <c>total</c> and the page it asked for.
/// </summary>
public static class LivePage01
{
    public const int PageSize = 100;

    /// <summary>Steps 1–5: request page 1, derive <c>maxPages = max(1, ceil(total/100))</c>, count duplicates, stop at the first of found = T, empty page, short page, or page = maxPages.</summary>
    public static async Task<LivePageResult> RunAsync(Func<int, Task<LivePage>> fetch, IReadOnlyCollection<string> targets)
    {
        var wanted = targets.ToHashSet(StringComparer.Ordinal); var found = new HashSet<string>(StringComparer.Ordinal); var seen = new HashSet<string>(StringComparer.Ordinal);
        var pages = 0; var duplicates = 0; var page = 1; var first = await fetch(1); var maxPages = Math.Max(1, (int)Math.Ceiling(first.Total / (double)PageSize)); var response = first;
        while (true)
        {
            foreach (var id in response.Ids) { if (!seen.Add(id)) duplicates++; if (wanted.Contains(id)) found.Add(id); }
            pages++;
            if (pages > maxPages) throw new InvalidOperationException("LIVE_PAGE_01_EXCEEDED_MAX_PAGES");
            if (found.Count == wanted.Count || response.Ids.Count == 0 || response.Ids.Count < PageSize || page == maxPages) break;
            page++; response = await fetch(page);
        }
        var missing = wanted.Except(found).OrderBy(x => x, StringComparer.Ordinal).ToArray();
        return new LivePageResult(wanted.Count, found.Count, pages, maxPages, missing.Length, duplicates, seen.Except(wanted).Count(), missing);
    }

    /// <summary>Reads EVERY page the envelope announces (ceil(total/100) requests) and returns the ids with the page each came from, duplicates included, for global integrity checks.</summary>
    public static async Task<(List<(string Id, int Page)> Rows, int Total, int Requests)> CollectAllAsync(Func<int, Task<LivePage>> fetch)
    {
        var first = await fetch(1); var maxPages = Math.Max(1, (int)Math.Ceiling(first.Total / (double)PageSize));
        var rows = first.Ids.Select(id => (id, 1)).ToList();
        for (var page = 2; page <= maxPages; page++) rows.AddRange((await fetch(page)).Ids.Select(id => (id, page)));
        return (rows, first.Total, maxPages);
    }
}


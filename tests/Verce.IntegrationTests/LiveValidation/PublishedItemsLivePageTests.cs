    private static readonly string[] Seeded = Enumerable.Range(0, Expected).Select(i => $"MLB{i:0000}").ToArray();

    /// <summary>A synthetic server over <see cref="Seeded"/>: <paramref name="shape"/> may corrupt each page it returns.</summary>
    private static Func<int, Task<LivePage>> Server(Func<int, string[], int, (string[] Ids, int Total)>? shape = null, Func<string[], string[]>? order = null)
    {
        var sorted = order is null ? Seeded : order(Seeded);
        return page =>
        {
            var ids = sorted.Skip((page - 1) * 100).Take(100).ToArray(); var total = Expected;
            if (shape is not null) (ids, total) = shape(page, ids, total);
            return Task.FromResult(new LivePage(ids, page, LivePage01.PageSize, total));
        };
    }

    /// <summary>A reproducible pseudo-random order: SHA-256 of the id (string.GetHashCode is randomized per process and would make a failure unrepeatable).</summary>
    private static string StableDigest(string id) => Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(id)));

    private static async Task<(int Missing, int Duplicate, int Unexpected, int Unique, int Total)> GlobalAsync(Func<int, Task<LivePage>> fetch)
    {
        var (rows, total, _) = await LivePage01.CollectAllAsync(fetch); var ids = rows.Select(r => r.Id).ToList(); var unique = ids.ToHashSet(StringComparer.Ordinal); var expected = Seeded.ToHashSet(StringComparer.Ordinal);
        return (expected.Except(unique).Count(), ids.Count - unique.Count, unique.Except(expected).Count(), unique.Count, total);
    }

    [Fact]
    public async Task The_helper_passes_a_correct_server_in_any_order_and_flags_every_listed_regression()
    {
        // Correct server, three different orders: identity-based, so all pass and each target is found.
        foreach (var order in new Func<string[], string[]>?[] { null, ids => ids.Reverse().ToArray(), ids => ids.OrderBy(StableDigest, StringComparer.Ordinal).ToArray(), ids => ids.OrderBy(i => (i.Length * 31 + i[^1]) % 7).ThenBy(i => i, StringComparer.Ordinal).ToArray() })
        {
            var fetch = Server(order: order); var global = await GlobalAsync(fetch);
            global.Should().Be((0, 0, 0, Expected, Expected));
            (await LivePage01.RunAsync(fetch, [Seeded[10], Seeded[140]])).MissingCount.Should().Be(0);
        }

        // 1. an item missing from page 2
        (await GlobalAsync(Server((p, ids, t) => (p == 2 ? ids.Skip(1).ToArray() : ids, t)))).Missing.Should().Be(1);
        // 2. an item duplicated (page 2 repeats one id of page 1 in place of its own)
        var dup = await GlobalAsync(Server((p, ids, t) => (p == 2 ? ids.Skip(1).Prepend(Seeded[0]).ToArray() : ids, t))); dup.Duplicate.Should().Be(1); dup.Missing.Should().Be(1);
        // ...and the helper's OWN duplicateCount reports it too (a target that is not there forces the full traversal), as do unexpected ids
        var helperDup = await LivePage01.RunAsync(Server((p, ids, t) => (p == 2 ? ids.Skip(1).Prepend(Seeded[0]).ToArray() : ids, t)), ["MLB-NOT-THERE"]);
        helperDup.DuplicateCount.Should().Be(1); helperDup.MissingCount.Should().Be(1); helperDup.Pages.Should().Be(2);
        // 3. an unexpected item
        var extra = await GlobalAsync(Server((p, ids, t) => (p == 2 ? ids.Append("MLB-UNEXPECTED").ToArray() : ids, t))); extra.Unexpected.Should().Be(1);
        // 4. an incorrect total
        (await GlobalAsync(Server((p, ids, t) => (ids, 149)))).Total.Should().Be(149);
        // 6./7. page 2 incomplete / page 2 repeating page 1: a target that only page 2 holds is reported missing
        (await LivePage01.RunAsync(Server((p, ids, t) => (p == 2 ? ids.Take(10).ToArray() : ids, t)), [Seeded[149]])).MissingCount.Should().Be(1);
        (await LivePage01.RunAsync(Server((p, ids, t) => (p == 2 ? Seeded.Take(50).ToArray() : ids, t)), [Seeded[149]])).MissingCount.Should().Be(1);
        // 8. a search limited to the first page never finds X, and is reported, not silently passed
        (await LivePage01.RunAsync(Server((p, ids, t) => (p > 1 ? [] : ids, t)), [Seeded[120]])).MissingCount.Should().Be(1);
        // page 2 is a full repeat of page 1: the helper's own duplicateCount sees all 100, and the global scan sees 50 omissions
        Func<int, string[], int, (string[], int)> repeatPage1 = (p, ids, t) => (p == 2 ? Seeded.Take(100).ToArray() : ids, t);
        var repeated = await LivePage01.RunAsync(Server(repeatPage1), ["MLB-NOT-THERE"]); repeated.DuplicateCount.Should().Be(100); repeated.Pages.Should().Be(2);
        (await GlobalAsync(Server(repeatPage1))).Missing.Should().Be(50);
    }

    [Fact]
    public async Task The_helper_never_issues_more_than_ceil_total_over_100_requests_even_when_the_server_keeps_serving_full_pages()
    {
        // A server that returns a FULL page of fresh ids for every page number and announces total=150: only the maxPages bound (not a short or empty page) can stop the traversal.
        var calls = 0; Func<int, Task<LivePage>> endless = p => { calls++; return Task.FromResult(new LivePage(Enumerable.Range(0, 100).Select(i => $"MLB-P{p}-{i}").ToArray(), p, LivePage01.PageSize, 150)); };
        var result = await LivePage01.RunAsync(endless, ["MLB-NOT-THERE"]);
        calls.Should().Be(2, "ceil(150/100) = 2"); result.Pages.Should().Be(2); result.MaxPages.Should().Be(2); result.MissingCount.Should().Be(1);

        // total=1 and total=0 still read page 1 (maxPages = max(1, ...)) and never a second page
        foreach (var total in new[] { 0, 1, 100 })
        {
            calls = 0; Func<int, Task<LivePage>> single = p => { calls++; return Task.FromResult(new LivePage(Enumerable.Range(0, 100).Select(i => $"MLB-Q{p}-{i}").ToArray(), p, LivePage01.PageSize, total)); };
            await LivePage01.RunAsync(single, ["MLB-NOT-THERE"]); calls.Should().Be(1, $"total={total} announces a single page");
        }
    }

